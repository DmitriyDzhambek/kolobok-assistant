function normQ(s: string): string {
	return s.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

/** Поиск по названию, синонимам и ингредиентам; пустой запрос — топ популярности. */
export function searchRecipes(query: string): Recipe[] {
	const q = normQ(query);
	if (!q) return [...RECIPES].sort((a, b) => b.pop - a.pop);
	const scored = RECIPES.map((r) => {
		const keys = [normQ(r.title), ...r.keys.map(normQ)];
		let s = 0;
		for (const k of keys) {
			if (k === q) s = Math.max(s, 1000);
			else if (k.startsWith(q) || q.startsWith(k)) s = Math.max(s, 600);
			else if (k.includes(q) || q.includes(k)) s = Math.max(s, 300);
		}
		if (!s && r.ingredients.some((i) => normQ(i).includes(q))) s = 120;
		return { r, s };
	}).filter((x) => x.s > 0);
	scored.sort((a, b) => b.s - a.s || b.r.pop - a.r.pop);
	return scored.map((x) => x.r);
}

/** Лучшее совпадение для голосовой команды; null — если ничего не найдено. */
export function findRecipe(query: string): Recipe | null {
	const q = normQ(query);
	if (!q) return null;
	return searchRecipes(q)[0] ?? null;
}

/** Категория по словам запроса («супы», «десерты», «выпечка»…). */
export function findCategory(query: string): CategoryId | null {
	const q = normQ(query);
	if (!q) return null;
	for (const c of CATEGORIES) {
		const label = normQ(c.label);
		if (label === q || label.includes(q) || q.includes(label)) return c.id;
		for (const k of c.keys) {
			if (k === q || q.includes(k) || (k.length >= 4 && k.includes(q)))
				return c.id;
		}
	}
	return null;
}
